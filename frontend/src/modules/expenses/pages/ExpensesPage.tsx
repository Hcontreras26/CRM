/** «De quién es», como valor de un desplegable: `p:7` campus, `e:3` empresa, `g` general. */
type Destino = string;
const destinoDe = (e: { project_id?: number | null; issuer_id?: number | null }): Destino =>
  e.project_id ? `p:${e.project_id}` : e.issuer_id ? `e:${e.issuer_id}` : 'g';

interface ExpenseDialogProps {
  open: boolean;
  onClose: () => void;
  expense: Expense | null;
  activeProjectId: number | null;
  activeIssuer: Ctx['activeIssuer'];
  projects: Proyecto[];
  puedeGeneral: boolean;
  onSaved?: () => void;
}

interface FormState {
  concepto: string;
  importe: string;
  categoria: ExpenseCategory;
  fecha: string;
  destino: Destino;
  notas: string;
  comprobante_url: string | null;
  comprobante_key: string | null;
  comprobante_mime: string | null;
  comprobante_size_bytes: number | null;
}

function hoyIso() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

function ExpenseDialog({ open, onClose, expense, activeProjectId, activeIssuer, projects, puedeGeneral, onSaved }: ExpenseDialogProps) {
  useEscapeKey(onClose, open);
  const [saving, setSaving] = useState(false);
  const [uploading, setUploading] = useState(false);

  // Dónde se puede apuntar. Con una empresa en la cabecera: la empresa entera
  // o uno de sus campus. Sin empresa: las empresas y los campus de la persona,
  // y «General» solo para quien ve todo el CRM (el servidor lo exige igual).
  const opciones = useMemo(() => {
    const campus = activeIssuer ? activeIssuer.campus : projects;
    const empresas = new Map<number, string>();
    for (const p of campus) {
      if (p.sociedad_emisora_id) empresas.set(Number(p.sociedad_emisora_id), p.sociedad_nombre || `Empresa #${p.sociedad_emisora_id}`);
    }
    if (activeIssuer) empresas.set(activeIssuer.id, activeIssuer.nombre);
    const ops: Array<{ value: Destino; label: string }> = [];
    if (puedeGeneral && !activeIssuer) ops.push({ value: 'g', label: 'General (todo el CRM)' });
    for (const [id, nombre] of empresas) ops.push({ value: `e:${id}`, label: `${nombre} — toda la empresa` });
    for (const p of campus) ops.push({ value: `p:${p.id}`, label: p.nombre || `Campus #${p.id}` });
    // Al editar, lo que ya tenía aunque no esté entre las opciones de hoy.
    if (expense) {
      const actual = destinoDe(expense);
      if (!ops.some((o) => o.value === actual)) ops.unshift({ value: actual, label: deQuien(expense) });
    }
    return ops;
  }, [activeIssuer, projects, puedeGeneral, expense]);

  const destinoPorDefecto = (): Destino => {
    if (activeProjectId) return `p:${activeProjectId}`;
    if (activeIssuer) return `e:${activeIssuer.id}`;
    return opciones[0]?.value ?? 'g';
  };

  const vacio = (): FormState => ({
    concepto: '',
    importe: '',
    categoria: 'otros',
    fecha: hoyIso(),
    destino: destinoPorDefecto(),
    notas: '',
    comprobante_url: null,
    comprobante_key: null,
    comprobante_mime: null,
    comprobante_size_bytes: null,
  });
  const [form, setForm] = useState<FormState>(vacio);

  useEffect(() => {
    if (!open) return;
    if (expense) {
      setForm({
        concepto: expense.concepto,
        importe: String(expense.importe),
        categoria: expense.categoria,
        fecha: String(expense.fecha).slice(0, 10),
        destino: destinoDe(expense),
        notas: expense.notas || '',
        comprobante_url: expense.comprobante_url || null,
        comprobante_key: expense.comprobante_key || null,
        comprobante_mime: expense.comprobante_mime || null,
        comprobante_size_bytes: expense.comprobante_size_bytes || null,
      });
    } else {
      setForm(vacio());
    }
  }, [open, expense, activeProjectId, activeIssuer?.id]);

  if (!open) return null;

  async function handleFileChange(ev: React.ChangeEvent<HTMLInputElement>) {
    const file = ev.target.files?.[0];
    if (!file) return;
    const allowed = ['application/pdf', 'image/jpeg', 'image/png', 'image/webp'];
    if (!allowed.includes(file.type)) {
      toast({ title: 'Formato no permitido', description: 'Solo PDF, JPG, PNG, WEBP.', variant: 'destructive' });
      return;
    }
    // El mismo tope que el servidor (10 MB). Antes la pantalla decía 15.
    if (file.size > 10 * 1024 * 1024) {
      toast({ title: 'Archivo muy grande', description: 'Máximo 10 MB.', variant: 'destructive' });
      return;
    }
    setUploading(true);
    try {
      const res = await expensesApi.uploadComprobante(file);
      if (res.success && res.data) {
        const d = res.data;
        setForm((f) => ({
          ...f,
          comprobante_url: d.comprobante_url,
          comprobante_key: d.comprobante_key,
          comprobante_mime: d.comprobante_mime,
          comprobante_size_bytes: d.comprobante_size_bytes,
        }));
        toast({ title: 'Comprobante subido' });
      }
    } catch (err) {
      const e = err as { data?: { error?: string }; message?: string };
      toast({ title: 'Error subiendo comprobante', description: e?.data?.error || e?.message, variant: 'destructive' });
    } finally {
      setUploading(false);
      ev.target.value = '';
    }
  }

  function removeComprobante() {
    setForm((f) => ({ ...f, comprobante_url: null, comprobante_key: null, comprobante_mime: null, comprobante_size_bytes: null }));
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault();
    if (!form.concepto.trim() || !form.importe) return;
    setSaving(true);
    try {
      const [tipo, id] = form.destino.split(':');
      const payload = {
        concepto: form.concepto.trim(),
        importe: Number(form.importe),
        categoria: form.categoria,
        fecha: form.fecha,
        project_id: tipo === 'p' ? Number(id) : null,
        issuer_id: tipo === 'e' ? Number(id) : null,
        notas: form.notas || null,
        comprobante_url: form.comprobante_url,
        comprobante_key: form.comprobante_key,
        comprobante_mime: form.comprobante_mime,
        comprobante_size_bytes: form.comprobante_size_bytes,
      };
      if (expense) {
        await expensesApi.update(expense.id, payload);
        toast({ title: 'Egreso actualizado' });
      } else {
        await expensesApi.create(payload);
        toast({ title: 'Egreso registrado', description: fmt(payload.importe) });
      }
      onSaved?.();
      onClose();
    } catch (err) {
      toast({ title: 'Error', description: (err as { data?: { error?: string } })?.data?.error, variant: 'destructive' });
    } finally {
      setSaving(false);
    }
  }

  return (
    <Portal>
      <div role="dialog" aria-modal="true" aria-labelledby="titulo-egreso" className="fixed inset-0 !m-0 z-[70] flex items-center justify-center sm:p-4">
        <div className="fixed inset-0 !m-0 bg-black/50 backdrop-blur-sm" onClick={onClose} />
        <div className="relative bg-card rounded-lg border border-border w-full max-w-md mx-4 p-6 max-h-[90vh] overflow-y-auto">
          <div className="flex items-center justify-between mb-4">
            <h2 id="titulo-egreso" className="text-lg font-semibold">{expense ? 'Editar egreso' : 'Nuevo egreso'}</h2>
            <button
              onClick={onClose}
              aria-label="Cerrar"
              className="p-1.5 rounded-lg hover:bg-muted focus:outline-none focus:ring-2 focus:ring-primary/40"
            >
              <X size={18} weight="bold" />
            </button>
          </div>

          <form onSubmit={handleSubmit} className="space-y-3">
            <div>
              <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">Concepto *</label>
              <input value={form.concepto} onChange={(e) => setForm({ ...form, concepto: e.target.value })} placeholder="Alquiler oficina, salarios enero..." className={inputClass} required autoFocus />
            </div>

            <div className="grid grid-cols-2 gap-3">
              <div>
                <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">Importe (EUR) *</label>
                <input type="number" step="0.01" min="0.01" value={form.importe} onChange={(e) => setForm({ ...form, importe: e.target.value })} className={inputClass + ' tabular-nums'} required />
              </div>
              <div>
                <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">Fecha *</label>
                <input type="date" value={form.fecha} onChange={(e) => setForm({ ...form, fecha: e.target.value })} className={inputClass} required />
              </div>
            </div>

            <div>
              <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">De quién es *</label>
              <Select<string>
                value={form.destino}
                onChange={(v) => setForm({ ...form, destino: v })}
                options={opciones}
                ariaLabel="De quién es el egreso"
              />
              <p className="mt-1 px-1 text-[11px] text-muted-foreground">
                Un gasto de toda la empresa (alquiler, gestoría…) cuenta en la empresa y en cada uno de sus campus.
              </p>
            </div>

            <div>
              <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">Categoría</label>
              <Select<ExpenseCategory>
                value={form.categoria}
                onChange={(v) => setForm({ ...form, categoria: v })}
                options={MANUAL_CATEGORIES.map((c) => ({ value: c, label: etiquetaCategoria(c) }))}
                ariaLabel="Categoría"
              />
            </div>

            {/* Comprobante (PDF/JPG/PNG/WEBP, máx 10 MB) */}
            <div>
              <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">
                Comprobante <span className="text-muted-foreground/70">(opcional, PDF/JPG/PNG/WEBP)</span>
              </label>
              {form.comprobante_url ? (
                <div className="flex items-center gap-2 px-3 py-2 rounded-lg border border-border bg-muted/30 text-xs">
                  <Paperclip size={14} weight="bold" className="text-primary flex-shrink-0" />
                  <button type="button" onClick={() => abrirComprobante(form.comprobante_url!)}
                    className="flex-1 truncate text-left text-primary hover:underline">
                    {form.comprobante_key} {form.comprobante_size_bytes ? `· ${(form.comprobante_size_bytes / 1024).toFixed(0)} KB` : ''}
                  </button>
                  <button type="button" onClick={removeComprobante} aria-label="Quitar comprobante"
                    className="h-7 w-7 inline-flex items-center justify-center rounded hover:bg-muted text-muted-foreground hover:text-destructive">
                    <X size={13} weight="bold" />
                  </button>
                </div>
              ) : (
                <label className={`flex items-center gap-2 px-3 py-2 rounded-lg border border-dashed border-border bg-muted/20 text-xs cursor-pointer hover:bg-muted/40 ${uploading ? 'opacity-50 pointer-events-none' : ''}`}>
                  <UploadSimple size={14} weight="bold" className="text-muted-foreground" />
                  <span className="flex-1 text-muted-foreground">
                    {uploading ? 'Subiendo…' : 'Adjuntar comprobante (clic para seleccionar archivo)'}
                  </span>
                  <input type="file" accept=".pdf,.jpg,.jpeg,.png,.webp" onChange={handleFileChange} className="hidden" disabled={uploading} />
                </label>
              )}
            </div>

            <div>
              <label className="mb-1.5 block px-1 text-secundario text-muted-foreground">Notas</label>
              <textarea value={form.notas} onChange={(e) => setForm({ ...form, notas: e.target.value })} rows={2} className="w-full px-3 py-2 rounded-lg border border-border bg-muted/50 text-sm outline-none resize-none focus:border-primary focus:ring-2 focus:ring-primary/20" />
            </div>

            <div className="flex justify-end gap-2 pt-2">
              <button
                type="button"
                onClick={onClose}
                className="h-9 px-4 rounded-lg border border-border bg-card text-sm font-semibold hover:bg-muted focus:outline-none focus:ring-2 focus:ring-primary/40"
              >
                Cancelar
              </button>
              <button
                type="submit"
                disabled={saving || uploading || !opciones.length}
                className="h-9 px-4 rounded-lg bg-primary text-primary-foreground text-sm font-semibold hover:bg-primary/90 disabled:opacity-50 focus:outline-none focus:ring-2 focus:ring-primary/40"
              >
                {saving ? 'Guardando...' : (expense ? 'Guardar' : 'Crear egreso')}
              </button>
            </div>
          </form>
        </div>
      </div>
    </Portal>
  );
}
